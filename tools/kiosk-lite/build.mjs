// Builds the web kiosk's lite panel: the phone's panel (android/app/src/main/assets/www) for browsers without container
// queries and modern JavaScript, down to Firefox 68 ESR, the last Firefox for Android 4.4.
//
//   node build.mjs           writes agent/PhoneBox.Agent/kiosk-lite/
//   node build.mjs --check   fails when the committed files are out of date (CI)
//
// JavaScript: the same modules, bundled and lowered by esbuild (?., ??, ||=, numeric separators…), plus polyfills.
// CSS: the same style sheets. What Firefox 68 cannot evaluate (container query units, min() / max() / clamp(),
// color-mix(), @container, :has(), aspect-ratio) becomes a custom property or an attribute that polyfill.js fills in
// per element at runtime, from a table written here. Everything else is left as it is.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';
import postcss from 'postcss';

const here = dirname(fileURLToPath(import.meta.url));
const www = join(here, '../../android/app/src/main/assets/www');
const out = join(here, '../../agent/PhoneBox.Agent/kiosk-lite');
const TARGET = 'firefox68';
const banner = '/* Generated by tools/kiosk-lite/build.mjs from android/app/src/main/assets/www. Do not edit. */\n';

// ------------------------------------------------------------------ JavaScript
async function buildJs() {
  const r = await esbuild.build({
    entryPoints: [join(www, 'main.js')], bundle: true, format: 'esm', target: TARGET, write: false,
    charset: 'utf8', legalComments: 'none', logLevel: 'error',
  });
  return banner + r.outputFiles[0].text;
}

// ------------------------------------------------------------------ CSS
const CQ_UNIT = /(\d*\.?\d+)(cqw|cqh|cqi|cqb|cqmin|cqmax)\b/;
const MATH_FN = /(^|[^\w-])(min|max|clamp)\(/;
const NEEDS_EVAL = (v) => CQ_UNIT.test(v) || MATH_FN.test(v) || v.includes('color-mix(');
// selectors Firefox 68 does not know: a rule list with one of them would be dropped whole
const UNKNOWN_PSEUDO = /:focus-visible|:where\(/;

/** Splits on commas outside brackets. */
function splitTop(s) {
  const parts = []; let depth = 0, cur = '';
  for (const ch of s) {
    if (ch === '(' || ch === '[') depth++;
    if (ch === ')' || ch === ']') depth--;
    if (ch === ',' && depth === 0) { parts.push(cur.trim()); cur = ''; } else cur += ch;
  }
  if (cur.trim()) parts.push(cur.trim());
  return parts;
}

/** Expands :is(a, b) into separate selectors (Firefox 68 has no :is). */
function expandIs(sel) {
  const i = sel.indexOf(':is(');
  if (i < 0) return [sel];
  let depth = 0, j = i + 3;
  for (; j < sel.length; j++) { if (sel[j] === '(') depth++; else if (sel[j] === ')' && --depth === 0) break; }
  const inner = splitTop(sel.slice(i + 4, j));
  return inner.flatMap((alt) => expandIs(sel.slice(0, i) + alt + sel.slice(j + 1)));
}

/** The element a selector styles, for querySelectorAll: without pseudo-elements and state pseudo-classes. */
function subjectSelector(sel) {
  return sel.replace(/::?(before|after|placeholder|selection|-webkit-[\w-]+|-moz-[\w-]+)\b/g, '')
    .replace(/:(hover|active|focus|focus-within|visited|checked|disabled)\b/g, '').trim() || '*';
}

/** Appends an attribute test to the subject of a selector, before any pseudo-element. */
function onSubject(sel, test) {
  const m = /::?(before|after|placeholder|-webkit-[\w-]+|-moz-[\w-]+)\b.*$/.exec(sel);
  return m ? sel.slice(0, m.index) + test + sel.slice(m.index) : sel + test;
}

function ratioOf(v) {
  const [a, b = '1'] = v.split('/').map((x) => parseFloat(x));
  return a / b;
}

function parseContainerQuery(params) {
  // "(max-height: 80px)", "(min-height: 230px) and (min-width: 420px)"
  return params.split(/\band\b/).map((p) => {
    const m = /\(\s*(min|max)-(width|height)\s*:\s*([\d.]+)px\s*\)/.exec(p);
    if (!m) throw new Error('unsupported container query: ' + params);
    return [m[1], m[2], +m[3]];
  });
}

async function buildCss() {
  const order = [...readFileSync(join(www, 'index.html'), 'utf8').matchAll(/<link rel="stylesheet" href="([^"]+)">/g)].map((m) => m[1]);
  const source = order.map((f) => readFileSync(join(www, f), 'utf8')).join('\n');
  // esbuild: nesting and vendor prefixes for the target
  const lowered = (await esbuild.transform(source, { loader: 'css', target: TARGET, charset: 'utf8', logLevel: 'error' })).code;
  const root = postcss.parse(lowered);

  const containers = new Set();   // selectors of query containers (container-type)
  const values = [];              // [selector, property, expression] → --pf-N
  const queries = [];             // [conditions, [selector…]] → data-pf-cq~="N"
  const has = [];                 // [selector, inner] → class pf-has-N
  const ratios = [];              // [selector, ratio, 'w' | 'h'] → inline width / height

  root.walkRules((rule) => {
    if (rule.parent?.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
    // Firefox 68: no :is(), :has(), :focus-visible, :where(); range inputs use -moz- pseudo-elements
    let sels = splitTop(rule.selector).flatMap(expandIs).filter((s) => !UNKNOWN_PSEUDO.test(s));
    sels = sels.map((s) => s.replace(/([^\s>+~,]*):has\(([^)]+)\)/g, (_, base, inner) => {
      has.push([base || '*', inner.trim()]);
      return `${base}.pf-has-${has.length - 1}`;
    }));
    const moz = sels.filter((s) => /::-webkit-slider-(runnable-track|thumb)/.test(s))
      .map((s) => s.replace('::-webkit-slider-runnable-track', '::-moz-range-track').replace('::-webkit-slider-thumb', '::-moz-range-thumb'));
    if (moz.length) rule.cloneAfter({ selector: moz.join(', ') });
    if (!sels.length) { rule.remove(); return; }
    rule.selector = sels.join(', ');

    rule.walkDecls((d) => {
      if (d.prop === 'container-type') { sels.forEach((s) => containers.add(subjectSelector(s))); d.remove(); return; }
      if (d.prop === 'aspect-ratio') {
        const sets = (p) => rule.nodes.some((n) => n.type === 'decl' && n.prop === p && n.value !== 'auto');
        ratios.push([sels.map(subjectSelector).join(', '), ratioOf(d.value), sets('width') && !sets('height') ? 'h' : 'w']);
        d.remove();
        return;
      }
      if (NEEDS_EVAL(d.value)) {
        values.push([sels.map(subjectSelector).join(', '), d.prop, d.value]);
        d.value = `var(--pf-${values.length - 1})`;
      }
    });
  });

  // @container (…) { rules } → the same rules on elements whose container matches, marked by polyfill.js
  root.walkAtRules('container', (at) => {
    const conditions = parseContainerQuery(at.params);
    const n = queries.length;
    const subjects = [];
    at.walkRules((rule) => {
      const sels = splitTop(rule.selector);
      subjects.push(...sels.map(subjectSelector));
      rule.selector = sels.map((s) => onSubject(s, `[data-pf-cq~="${n}"]`)).join(', ');
    });
    queries.push([conditions, subjects.join(', ')]);
    at.replaceWith(at.nodes);
  });

  const table = { containers: [...containers].join(', '), values, queries, has, ratios };
  return { css: banner + root.toString(), table };
}

// ES5: browsers that cannot run even the lite panel (no ES modules or CSS custom properties) get an explanation.
const TOO_OLD = `<script>(function(){var ok=false;try{ok='noModule' in HTMLScriptElement.prototype&&!!(window.CSS&&CSS.supports&&CSS.supports('color','var(--x)'));}catch(e){}if(ok)return;document.addEventListener('DOMContentLoaded',function(){document.body.innerHTML='<div style="font:18px sans-serif;color:#e8eaf0;background:#0b0d12;position:fixed;top:0;left:0;right:0;bottom:0;padding:24px;line-height:1.5">'+'<b>This browser is too old for the PhoneBox kiosk.</b><br>On Android 4.4, install Firefox 68 (the last version for Android 4.4) and open this address there. On other devices, use a current browser.</div>';});})();</script>`;

// ------------------------------------------------------------------ assemble
async function build() {
  const [js, { css, table }] = await Promise.all([buildJs(), buildCss()]);
  const polyfill = banner + `window.PF_TABLE = ${JSON.stringify(table)};\n` + readFileSync(join(here, 'polyfill.js'), 'utf8');
  const index = readFileSync(join(www, 'index.html'), 'utf8')
    .replace(/(<link rel="stylesheet" href="[^"]+">\n?)+/, '<link rel="stylesheet" href="style.css">\n')
    .replace('<script type="module" src="main.js"></script>', '<script src="polyfill.js"></script>\n<script type="module" src="main.js"></script>')
    .replace('<head>', '<head>\n<!-- Generated by tools/kiosk-lite/build.mjs: the phone\'s panel for older browsers (web kiosk lite). -->\n' + TOO_OLD);
  return { 'index.html': index, 'main.js': js, 'style.css': css, 'polyfill.js': polyfill };
}

const files = await build();
if (process.argv.includes('--check')) {
  const stale = Object.entries(files).filter(([f, text]) => !existsSync(join(out, f)) || readFileSync(join(out, f), 'utf8') !== text).map(([f]) => f);
  if (stale.length) { console.error(`kiosk-lite is out of date (${stale.join(', ')}): run  node tools/kiosk-lite/build.mjs`); process.exit(1); }
  console.log('kiosk-lite is up to date');
} else {
  mkdirSync(out, { recursive: true });
  for (const [f, text] of Object.entries(files)) writeFileSync(join(out, f), text);
  const t = JSON.parse(files['polyfill.js'].match(/PF_TABLE = (.*);\n/)[1]);
  console.log(`kiosk-lite written: ${t.values.length} computed values, ${t.queries.length} container queries, ${t.has.length} :has, ${t.ratios.length} aspect ratios`);
}
